export const locales = ["ru", "en"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "ru";

export function isLocale(value: string): value is Locale {
  return locales.includes(value as Locale);
}

export function getLocale(params: { locale?: string }): Locale {
  if (params.locale && isLocale(params.locale)) return params.locale;
  return defaultLocale;
}

export function ruPlural(n: number, one: string, few: string, many: string) {
  const abs = Math.abs(Math.trunc(n)) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

export function resultsLabel(locale: Locale, n: number) {
  if (locale === "en") return n === 1 ? "item" : "items";
  return ruPlural(n, "позиция", "позиции", "позиций");
}

export function subcatsLabel(locale: Locale, n: number) {
  if (locale === "en") return n === 1 ? "subcategory" : "subcategories";
  return ruPlural(n, "подкатегория", "подкатегории", "подкатегорий");
}

export function catsLabel(locale: Locale, n: number) {
  if (locale === "en") return n === 1 ? "category" : "categories";
  return ruPlural(n, "категория", "категории", "категорий");
}

export function productsLabel(locale: Locale, n: number) {
  if (locale === "en") return n === 1 ? "product" : "products";
  return ruPlural(n, "товар", "товара", "товаров");
}

